"""Interaction rank of an evaluation cost and the rate of low-dimensional coding surfaces.

The script checks, on the 96-state nonuniform circle of the letter, which finite Gibbs
encoders with a d-dimensional bilinear coding cost reach the finite Blahut optimum when
every method is scored by the same squared-arc evaluator.

    python experiments/interaction_rank.py --output results/interaction_rank.json

Slopes are in nats of information per unit distortion as in the preserved early study,
rates are reported in bits per state, and matched-distortion values interpolate the
achieved (distortion, information) points of the same 25 slopes.
"""
import argparse
import json
import warnings
from pathlib import Path

import numpy as np
from scipy.optimize import linprog, minimize
from scipy.special import logsumexp

# NumPy 2.0 with Accelerate emits spurious floating-point flags inside matmul on arm64.
warnings.filterwarnings("ignore", message=".*encountered in matmul")
LN2 = float(np.log(2.0))
TINY = 1e-300


def center(matrix):
    """Remove row means and column means and add the grand mean (the projection H T H)."""
    return matrix - matrix.mean(1, keepdims=True) - matrix.mean(0, keepdims=True) + matrix.mean()


def gibbs(log_mass, cost, scale):
    logits = log_mass[None, :] - scale * cost
    return np.exp(logits - logsumexp(logits, axis=1)[:, None])


def marginal(p, channel):
    return np.einsum("i,ij->j", p, channel)


def information_nats(p, channel):
    out = marginal(p, channel)
    ratio = np.log(np.maximum(channel, TINY)) - np.log(np.maximum(out, TINY))[None, :]
    return float(np.sum(p[:, None] * channel * ratio))


def distortion(p, channel, evaluator):
    return float(np.sum(p[:, None] * channel * evaluator))


def blahut(p, cost, beta, tol=2e-10, maxiter=10000):
    """Output marginal of the Blahut iteration for I + beta*D in nats."""
    pi = np.full(cost.shape[1], 1.0 / cost.shape[1])
    for _ in range(maxiter):
        new = marginal(p, gibbs(np.log(np.maximum(pi, TINY)), cost, beta))
        done = np.max(np.abs(new - pi)) < tol
        pi = new
        if done:
            break
    return pi


def blahut_value_nats(p, cost, beta, pi):
    """Dual lower bound and achieved Lagrangian of the kernel generated by ``pi``."""
    logits = np.log(np.maximum(pi, TINY))[None, :] - beta * cost
    logz = logsumexp(logits, axis=1)
    channel = np.exp(logits - logz[:, None])
    upper = information_nats(p, channel) + beta * distortion(p, channel, cost)
    slack = np.max(np.einsum("i,ij->j", p, np.exp(-beta * cost - logz[:, None])))
    lower = float(-np.dot(p, logz) - np.log(max(slack, 1.0)))
    return lower, upper


def stability_constant_bits(rho):
    """Additive constant of the ratio-based comparison between two coding costs."""
    growth = np.exp(rho) - 1.0
    return float((growth * 2.0 / np.e + min(rho, growth**2)) / LN2)


def interaction_sup(delta):
    """Smallest max-entry distance from ``delta`` to additively separable matrices (an LP)."""
    n, m = delta.shape
    count = n + m + 1
    pick = np.zeros((n * m, count))
    index = np.arange(n * m)
    pick[index, index // m] = 1.0
    pick[index, n + index % m] = 1.0
    upper = pick.copy()
    upper[:, -1] = -1.0  # a_i + b_j - t <= delta_ij
    lower = -pick
    lower[:, -1] = -1.0  # -(a_i + b_j) - t <= -delta_ij
    flat = delta.reshape(-1)
    target = np.zeros(count)
    target[-1] = 1.0
    bounds = [(None, None)] * (n + m) + [(0, None)]
    out = linprog(
        target,
        A_ub=np.vstack([upper, lower]),
        b_ub=np.concatenate([flat, -flat]),
        bounds=bounds,
        method="highs",
    )
    if not out.success:
        raise RuntimeError(out.message)
    return float(out.x[-1])


def fit(p, evaluator, cost, beta, log_mass, log_scale, learn_mass=True):
    """Minimize I + beta*D_g (nats) over masses and scale by the covariance first variation."""

    def objective(v):
        lm = v[:-1] if learn_mass else log_mass
        scale = float(np.exp(v[-1]))
        channel = gibbs(lm, cost, scale)
        out = marginal(p, channel)
        score = (
            np.log(np.maximum(channel, TINY))
            - np.log(np.maximum(out, TINY))[None, :]
            + beta * evaluator
        )
        value = float(np.sum(p[:, None] * channel * score))
        centred = score - np.sum(channel * score, axis=1, keepdims=True)
        grad_mass = marginal(p, channel * centred) if learn_mass else np.zeros(len(log_mass))
        grad_scale = float(np.sum(p[:, None] * channel * centred * (-scale * cost)))
        return value, np.concatenate([grad_mass, [grad_scale]])

    start = np.concatenate([log_mass, [log_scale]])
    bounds = [(-60.0, 60.0)] * len(log_mass) + [(-9.0, 8.0)]
    out = minimize(
        objective,
        start,
        jac=True,
        method="L-BFGS-B",
        bounds=bounds,
        options={"maxiter": 5000, "maxfun": 20000, "ftol": 1e-15, "gtol": 1e-9},
    )
    lm = out.x[:-1] if learn_mass else log_mass
    return gibbs(lm, cost, float(np.exp(out.x[-1]))), out


def circle(n=96, modulation=0.85):
    theta = 2 * np.pi * (np.arange(n) + 0.5) / n
    p = (1 + modulation * np.cos(theta)) / n
    gap = np.abs(theta[:, None] - theta[None, :])
    arc = np.minimum(gap, 2 * np.pi - gap)
    return p, arc


def matched(points, target):
    ordered = np.array(sorted(points))
    if not ordered[0, 0] <= target <= ordered[-1, 0]:
        return None
    return float(np.interp(target, ordered[:, 0], ordered[:, 1]))


def sweep(p, evaluator, cost, betas, learn_mass):
    """Achieved (D_g, bits) of one coding cost over all slopes."""
    points = []
    for beta in betas:
        if learn_mass:
            start = np.log(np.maximum(blahut(p, cost, beta), 1e-30))
        else:
            start = np.zeros(cost.shape[1])
        channel, _ = fit(p, evaluator, cost, beta, start, float(np.log(beta)), learn_mass)
        points.append((distortion(p, channel, evaluator), information_nats(p, channel) / LN2))
    return points


def pythagoras(p, evaluator, cost, beta, pi_star):
    """Excess Lagrangian (bits) of the surface whose masses cancel the column term at scale beta.

    Returns the exact excess, the row-averaged divergence that upper bounds it and the
    sup-norm bound eps^2/(2 ln 2) computed from the doubly centred logit residual.
    """
    star = gibbs(np.log(np.maximum(pi_star, TINY)), evaluator, beta)
    residual = center(beta * (cost - evaluator))
    tilted = star * np.exp(-residual)
    tilted /= tilted.sum(1, keepdims=True)
    row = np.sum(tilted * (np.log(np.maximum(tilted, TINY)) - np.log(np.maximum(star, TINY))), 1)
    weighted = float(np.dot(p, row)) / LN2
    out, out_star = marginal(p, tilted), marginal(p, star)
    correction = float(np.sum(out * (np.log(np.maximum(out, TINY)) - np.log(np.maximum(out_star, TINY))))) / LN2
    value = (information_nats(p, tilted) + beta * distortion(p, tilted, evaluator)) / LN2
    optimum = (information_nats(p, star) + beta * distortion(p, star, evaluator)) / LN2
    eps = float(np.abs(residual).max())
    return {
        "excess_bits": value - optimum,
        "identity_bits": weighted - correction,
        "weighted_divergence_bits": weighted,
        "sup_residual_logit": eps,
        "sup_bound_bits": eps**2 / (2 * LN2),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("results/interaction_rank.json"))
    parser.add_argument("--target", type=float, default=0.30)
    parser.add_argument("--dimensions", type=int, nargs="+", default=[2, 4, 8, 16, 32])
    args = parser.parse_args()

    p, arc = circle()
    evaluator = arc**2
    chord = 2 - 2 * np.cos(arc)
    betas = np.geomspace(0.25, 32, 25)
    interaction = center(evaluator)
    left, singular, right = np.linalg.svd(interaction)

    reference, gaps, supports = [], [], []
    stars = {}
    for beta in betas:
        pi = blahut(p, evaluator, beta)
        stars[float(beta)] = pi
        lower, upper = blahut_value_nats(p, evaluator, beta, pi)
        gaps.append(upper - lower)
        supports.append(int((pi > 1e-12).sum()))
        channel = gibbs(np.log(np.maximum(pi, TINY)), evaluator, beta)
        reference.append((distortion(p, channel, evaluator), information_nats(p, channel) / LN2))
    ordered = sorted(zip([r[0] for r in reference], betas, supports))
    near = min(ordered, key=lambda r: abs(r[0] - args.target))
    beta_near = float(near[1])

    result = {
        "source": {"states": 96, "modulation": 0.85, "evaluator": "squared shortest arc"},
        "slopes_nats": [float(b) for b in betas],
        "target_distortion": args.target,
        "blahut_bits": matched(reference, args.target),
        "blahut_max_dual_gap_nats": float(max(gaps)),
        "blahut_support_at_nearest_slope": int(near[2]),
        "nearest_slope_nats": beta_near,
        "nearest_slope_distortion": float(near[0]),
        "singular_values": [float(v) for v in singular[:40]],
        "numerical_rank": int(np.linalg.matrix_rank(interaction, tol=1e-8)),
        "negative_type": {
            "min_eig_minus_centered_arc_squared": float(np.linalg.eigvalsh(-interaction).min()),
            "min_eig_minus_centered_chord_squared": float(np.linalg.eigvalsh(-center(chord)).min()),
        },
        "families": {},
    }
    families = result["families"]
    families["fixed_surface_uniform_mass"] = {
        "bits": matched(sweep(p, evaluator, evaluator, betas, False), args.target)
    }
    families["fixed_surface_learned_mass"] = {
        "bits": matched(sweep(p, evaluator, evaluator, betas, True), args.target)
    }
    families["chord_uniform_mass"] = {
        "bits": matched(sweep(p, evaluator, chord, betas, False), args.target)
    }
    families["chord_learned_mass"] = {
        "bits": matched(sweep(p, evaluator, chord, betas, True), args.target),
        "note": "single Euclidean surface; scale optimized at every slope",
    }
    for d in args.dimensions:
        truncated = (left[:, :d] * singular[:d]) @ right[:d]
        residual = interaction - truncated
        cost = evaluator - residual  # equals the rank-d interaction plus a separable matrix
        entry = {
            "bits": matched(sweep(p, evaluator, cost, betas, True), args.target),
            "max_residual": float(np.abs(residual).max()),
            "next_singular_value": float(singular[d]),
            "at_nearest_slope": pythagoras(p, evaluator, cost, beta_near, stars[beta_near]),
        }
        entry["interaction_sup_lp"] = interaction_sup(residual)
        families[f"spectral_d{d}"] = entry
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf8")
    print(json.dumps(result["families"], indent=1))
    print("BA", result["blahut_bits"], "support", near[2], "beta", beta_near)


if __name__ == "__main__":
    main()
